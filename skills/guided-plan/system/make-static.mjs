#!/usr/bin/env node
// Writes static.generated.mjs: guide.css, runtime.js and features.css as strings, so the pure core
// (page.mjs) can draw a page with no file system. Those files stay the sources; after editing any
// of them, run:
//
//   node make-static.mjs
//
// The tests fail while static.generated.mjs is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { featureCss } from "./renderer.mjs";

const here = dirname(fileURLToPath(import.meta.url));
export const STATIC_PATH = join(here, "static.generated.mjs");

// The module's text for these two sources. JSON.stringify gives a JavaScript string literal.
export function staticSource(css, runtime, features = "") {
  return [
    "// Generated by make-static.mjs from guide.css, runtime.js and features.css. Do not edit; edit those",
    "// and run `node make-static.mjs`.",
    `export const GUIDE_CSS = ${JSON.stringify(css)};`,
    `export const RUNTIME_JS = ${JSON.stringify(runtime)};`,
    "// features.css, by feature: styles a page carries only when it uses them.",
    `export const FEATURE_CSS = ${JSON.stringify(featureCss(features))};`,
    "",
  ].join("\n");
}

export function currentStaticSource() {
  const read = (f) => readFileSync(join(here, f), "utf8");
  return staticSource(read("guide.css"), read("runtime.js"), read("features.css"));
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  writeFileSync(STATIC_PATH, currentStaticSource());
  console.log("static.generated.mjs written");
}
