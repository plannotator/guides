#!/usr/bin/env node
// Writes static.generated.mjs: guide.css and runtime.js as two strings, so the pure core (page.mjs)
// can draw a page with no file system. guide.css and runtime.js stay the sources; after editing
// either one, run:
//
//   node make-static.mjs
//
// The tests fail while static.generated.mjs is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const STATIC_PATH = join(here, "static.generated.mjs");

// The module's text for these two sources. JSON.stringify gives a JavaScript string literal.
export function staticSource(css, runtime) {
  return [
    "// Generated by make-static.mjs from guide.css and runtime.js. Do not edit; edit those and run",
    "// `node make-static.mjs`.",
    `export const GUIDE_CSS = ${JSON.stringify(css)};`,
    `export const RUNTIME_JS = ${JSON.stringify(runtime)};`,
    "",
  ].join("\n");
}

export function currentStaticSource() {
  return staticSource(readFileSync(join(here, "guide.css"), "utf8"), readFileSync(join(here, "runtime.js"), "utf8"));
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  writeFileSync(STATIC_PATH, currentStaticSource());
  console.log("static.generated.mjs written");
}
